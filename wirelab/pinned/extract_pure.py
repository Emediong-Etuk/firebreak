"""Build gemma4_parser_pinned.py by copying the pure parse functions *verbatim* (via ast
source segments) out of the pinned vLLM 0.19.1 gemma4_tool_parser.py. No hand edits:
the vendored file is a deterministic function of the pinned file."""
import ast, hashlib, sys
from pathlib import Path

SRC = Path(sys.argv[1]); OUT = Path(sys.argv[2])
text = SRC.read_text()
tree = ast.parse(text)
want_funcs = {"_parse_gemma4_value", "_parse_gemma4_args", "_parse_gemma4_array"}
want_consts = {"TOOL_CALL_START", "TOOL_CALL_END", "STRING_DELIM"}
parts = []
for node in tree.body:
    if isinstance(node, ast.Assign) and any(getattr(t, "id", None) in want_consts for t in node.targets):
        parts.append(ast.get_source_segment(text, node))
    if isinstance(node, ast.FunctionDef) and node.name in want_funcs:
        parts.append(ast.get_source_segment(text, node))
    if isinstance(node, ast.ClassDef) and node.name == "Gemma4ToolParser":
        for sub in ast.walk(node):
            if isinstance(sub, ast.Call) and getattr(sub.func, "attr", "") == "compile":
                regex_src = ast.get_source_segment(text, sub)
assert len(parts) == 6, parts
sha = hashlib.sha256(text.encode()).hexdigest()
header = f'''# SPDX-License-Identifier: Apache-2.0
# SPDX-FileCopyrightText: Copyright contributors to the vLLM project
# VENDORED, UNMODIFIED function bodies from vllm 0.19.1 vllm/tool_parsers/gemma4_tool_parser.py
# source sha256: {sha}
# Generated by wirelab/pinned/extract_pure.py -- do not edit by hand.
import json
import regex as re

'''
footer = f'''


# Non-streaming extraction regex, copied verbatim from Gemma4ToolParser.__init__
TOOL_CALL_REGEX = {regex_src}


def extract_tool_calls(model_output: str):
    """Mirror of Gemma4ToolParser.extract_tool_calls (non-streaming) minus vLLM types.
    Returns (tools_called, [(name, arguments_json)], content)."""
    if TOOL_CALL_START not in model_output:
        return False, [], model_output
    try:
        matches = TOOL_CALL_REGEX.findall(model_output)
        if not matches:
            return False, [], model_output
        calls = []
        for func_name, args_str in matches:
            arguments = _parse_gemma4_args(args_str)
            calls.append((func_name, json.dumps(arguments, ensure_ascii=False)))
        content_end = model_output.find(TOOL_CALL_START)
        content = model_output[:content_end].strip() if content_end > 0 else None
        return True, calls, content if content else None
    except Exception:
        return False, [], model_output
'''
OUT.write_text(header + "\n\n\n".join(parts) + footer)
print("wrote", OUT, "from", sha)
