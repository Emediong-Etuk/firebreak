"""F1 reproducer: array-parser hang in vLLM 0.19.1 gemma4 tool parser.

Runs each probe in a forked child with RLIMIT_AS, samples the child's RSS every 100 ms,
kills it at the watchdog deadline, and writes evidence/wirelab/F1.json + F1.md.
Usage: python -I wirelab/repro_f1.py [--seconds 3]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import multiprocessing as mp
import os
import platform
import resource
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PINNED = ROOT / "wirelab" / "pinned"
sys.path.insert(0, str(PINNED))

FULL_CALL_PLAIN = (
    '<|tool_call>call:get_code_subgraph{nodes:["rich.pretty.Node", "List[int]"]}<tool_call|>'
)
PROBES = [
    # (id, function, input, description)
    ("array_marker_quoted", "array", '<|"|>--detail<|"|>, <|"|>List[int]<|"|>',
     "marker-quoted items (the form the chat template teaches): control"),
    ("array_plain_quoted", "array", '"--detail", "List[int]"',
     "plain-quoted items with a bracket inside a string: the reported F1 input"),
    ("array_plain_bracket_min", "array", '"a]"',
     "minimal: one plain-quoted item containing a closing bracket"),
    ("extract_full_call", "extract", FULL_CALL_PLAIN,
     "end-to-end: non-streaming extract_tool_calls on a full model completion"),
]


def _rss_kb(pid: int) -> int:
    try:
        for line in open(f"/proc/{pid}/status"):
            if line.startswith("VmRSS:"):
                return int(line.split()[1])
    except FileNotFoundError:
        pass
    return 0


def _child(kind: str, s: str, q: mp.Queue) -> None:
    resource.setrlimit(resource.RLIMIT_AS, (4 << 30, 4 << 30))
    import gemma4_parser_pinned as p
    try:
        if kind == "array":
            out = p._parse_gemma4_array(s)
        else:
            out = p.extract_tool_calls(s)
        q.put(("RETURNED", repr(out)[:300]))
    except MemoryError:
        q.put(("MEMORYERROR", ""))


def run_probe(kind: str, s: str, seconds: float) -> dict:
    q: mp.Queue = mp.Queue()
    pr = mp.Process(target=_child, args=(kind, s, q))
    t0 = time.monotonic()
    pr.start()
    samples = []
    while pr.is_alive() and time.monotonic() - t0 < seconds:
        samples.append((round(time.monotonic() - t0, 2), _rss_kb(pr.pid)))
        time.sleep(0.1)
    elapsed = time.monotonic() - t0
    if pr.is_alive():
        pr.kill()
        pr.join()
        outcome, detail = "HANG", f"killed by watchdog after {elapsed:.2f}s"
    else:
        pr.join()
        outcome, detail = q.get() if not q.empty() else ("CRASH", f"exitcode={pr.exitcode}")
        if outcome == "RETURNED":
            outcome = "OK"
    growth = None
    if len(samples) >= 6:
        (t1, r1), (t2, r2) = samples[2], samples[-1]
        if t2 > t1:
            growth = round((r2 - r1) / 1024 / (t2 - t1), 1)
    return {"outcome": outcome, "detail": detail, "elapsed_s": round(elapsed, 3),
            "rss_growth_mb_per_s": growth, "rss_samples_kb": samples}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=float, default=3.0)
    args = ap.parse_args()
    hashes = json.loads((PINNED / "hashes.json").read_text())
    results = []
    for pid, kind, s, desc in PROBES:
        r = run_probe(kind, s, args.seconds)
        r.update({"id": pid, "function": "_parse_gemma4_array" if kind == "array" else "extract_tool_calls",
                  "input": s, "description": desc})
        results.append(r)
        print(f"{pid:26} {r['outcome']:6} {r['detail'][:60]:60} growth={r['rss_growth_mb_per_s']} MB/s")
    reproduced = any(r["outcome"] == "HANG" for r in results if r["id"] != "array_marker_quoted")
    control_ok = next(r for r in results if r["id"] == "array_marker_quoted")["outcome"] == "OK"
    out = {
        "fault": "F1",
        "reproduced": reproduced and control_ok,
        "watchdog_s": args.seconds,
        "pinned": {k: hashes[k] for k in ("vllm_wheel_competition", "gemma4_tool_parser.py")},
        "host": {"python": platform.python_version(), "machine": platform.machine()},
        "probes": results,
        "command": "python -I wirelab/repro_f1.py",
    }
    ev = ROOT / "evidence" / "wirelab"
    ev.mkdir(parents=True, exist_ok=True)
    (ev / "F1.json").write_text(json.dumps(out, indent=2) + "\n")
    rows = "\n".join(
        f"| `{r['id']}` | `{r['function']}` | `{r['input']}` | **{r['outcome']}** | {r['elapsed_s']} | {r['rss_growth_mb_per_s']} |"
        for r in results)
    md = f"""# F1: array-parser hang (generated by `wirelab/repro_f1.py`; do not edit)

**Reproduced on the pinned parser: {'YES' if out['reproduced'] else 'NO'}**

Pinned parser `vllm/tool_parsers/gemma4_tool_parser.py` sha256 `{hashes['gemma4_tool_parser.py']}`
(from the competition wheelhouse `vllm-0.19.1` wheel sha256 `{hashes['vllm_wheel_competition']}`; the
parser file is byte-identical in the PyPI wheel).

| probe | function | input | outcome | seconds | RSS growth MB/s |
|---|---|---|---|---|---|
{rows}

## Mechanism (read from the pinned source)
In `_parse_gemma4_array`, the bare-value branch scans `while arr_str[i] not in (",", "]")`.
A plain-quoted item that contains `]` stops *on* the `]`; the next loop iteration does not skip `]`,
re-enters the bare-value branch with zero progress, and appends `""` forever (unbounded list growth).
The marker-quoted form skips the whole string via `find(STRING_DELIM)`, so it returns.

## Why it kills the whole scoring run
`OpenAIServing._parse_tool_calls_from_content` (vllm/entrypoints/openai/engine/serving.py) calls
`extract_tool_calls` synchronously inside the async request handler, so the hang blocks the API
server's event loop for every in-flight and future request. swegemma wraps each agent session in
`asyncio.timeout(max_time_minutes*60)` (harness/agent_runner.py), so every later task burns its full
time budget with no model output.

## Reproduce
```
{out['command']}
```
"""
    (ev / "F1.md").write_text(md)
    return 0 if out["reproduced"] else 1


if __name__ == "__main__":
    sys.exit(main())
