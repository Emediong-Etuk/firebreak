"""Generate evidence/wirelab/F2.md + F2.json from Wire Lab outputs (no hand-typed numbers)."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
EV = ROOT / "evidence" / "wirelab"
s = json.loads((EV / "summary.json").read_text())
hashes = json.loads((ROOT / "wirelab/pinned/hashes.json").read_text())
calls = [json.loads(l) for l in open(ROOT / "wirelab/corpora/c2_gold/calls.jsonl")]
mins = [c for c in calls if c["kind"] in ("hunk", "new_file")]
tq = lambda c: any(isinstance(v, str) and ('"""' in v or "'''" in v) for v in c["args"].values())
endq = lambda c: any(isinstance(v, str) and v.rstrip().endswith(('"', "'")) for v in c["args"].values())
rep = {n: json.loads((EV / "reproducers" / f"{n}.json").read_text()) for n in ("early_close_rejected",)}
c3 = s["corpora"]["c3"]["by_op"]
faithful = s["corpora"]["c2"]["classes"]
out = {
    "fault": "F2",
    "reproduced_from_faithful_render": faithful["OK"] != s["corpora"]["c2"]["n"],
    "reproduced_under_model_deviation": any(c3[o].get("REJECTED", 0) for o in ("early_close_at_tq", "doubled_close_schema_order")),
    "gold_minimal_calls": len(mins),
    "gold_minimal_calls_with_triple_quote_arg": sum(map(tq, mins)),
    "gold_tasks_with_triple_quote_arg": len({c["task"] for c in mins if tq(c)}),
    "gold_minimal_calls_with_arg_ending_in_quote": sum(map(endq, mins)),
    "gold_tasks_with_arg_ending_in_quote": len({c["task"] for c in mins if endq(c)}),
    "c2_faithful": faithful,
    "c3_ops": {o: c3[o] for o in ("early_close_at_tq", "doubled_close", "doubled_close_schema_order")},
    "minimal_reproducer": rep["early_close_rejected"],
}
(EV / "F2.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
r = out["minimal_reproducer"]
md = f"""# F2 — docstring / quote mangling (generated by `wirelab/report_f2.py`; do not edit)

**Reproduced from faithful template renders: {'YES' if out['reproduced_from_faithful_render'] else 'NO'}**
({faithful['OK']}/{s['corpora']['c2']['n']} gold-replay calls rendered by the pinned chat template parse back exactly.)

**Reproduced under model-side emission deviations: {'YES' if out['reproduced_under_model_deviation'] else 'NO'}**, with the
exact reported signature: a junk key `<|"|>,filepath` and ADK's *"mandatory input parameters are not present: filepath"*.

| C3 operator (model drift) | outcome counts on the 129-task gold replay |
|---|---|
""" + "\n".join(f"| `{o}` | {json.dumps(v)} |" for o, v in out["c3_ops"].items()) + f"""

## Verdict
F2 is a **model-side emission fault**, not a parser bug: the template wraps strings in `<|"|>` with no
escaping, and the pinned parser reads a faithful render back exactly. When the model emits the
`<|"|>` token where content has a `"` (e.g. at the end of a docstring), the string closes early;
the stray marker becomes part of the next key, the real key is lost, and ADK rejects the call.
Because the model sees the same context on retry, it tends to emit the identical call again (retry storm).

## Exposure in the dev set (minimal gold fixes)
- {out['gold_minimal_calls_with_triple_quote_arg']} of {out['gold_minimal_calls']} minimal edit calls contain `\"\"\"`/`'''` in an argument
  ({out['gold_tasks_with_triple_quote_arg']} of 129 tasks).
- {out['gold_minimal_calls_with_arg_ending_in_quote']} calls have an argument that *ends* in a quote character
  ({out['gold_tasks_with_arg_ending_in_quote']} tasks); the shrunk minimal trigger is content `{r['minimal_content']}`.

## Minimal reproducer (Hypothesis-shrunk)
```
{r['text']}
```
→ **{r['outcome']}**: {r['detail']}

Pinned parser sha256 `{hashes['gemma4_tool_parser.py']}`; chat template sha256 `{hashes.get('chat_template.jinja', 'n/a')}`.

## Reproduce
```
python -I wirelab/run_lab.py --quick && python -I wirelab/shrink.py && python -I wirelab/report_f2.py
```
"""
(EV / "F2.md").write_text(md)
print(json.dumps({k: v for k, v in out.items() if k not in ("minimal_reproducer", "c3_ops")}))
